// Interpolation helper for any week from 1 to 40
export function getGestationalDataForWeek(weekNum) {
  const safeWeek = Math.max(1, Math.min(40, parseInt(weekNum, 10) || 20));
  
  if (PREGNANCY_WEEK_DATA[safeWeek]) {
    return PREGNANCY_WEEK_DATA[safeWeek];
  }
  
  // Find nearest anchor
  const keys = Object.keys(PREGNANCY_WEEK_DATA).map(Number).sort((a, b) => a - b);
  let closest = keys[0];
  for (const k of keys) {
    if (k <= safeWeek) closest = k;
  }
  const base = PREGNANCY_WEEK_DATA[closest];
  
  const trimester = safeWeek <= 12 ? 1 : (safeWeek <= 27 ? 2 : 3);
  const lengthEst = Math.round((safeWeek * 1.25) * 10) / 10;
  const weightEst = Math.round(Math.pow(safeWeek, 2.3) * 0.7);

  let fallbackFruit = "Little Sprout";
  let fallbackEmoji = "🌱";
  if (safeWeek >= 9 && safeWeek < 12) { fallbackFruit = "Lime"; fallbackEmoji = "🍋"; }
  else if (safeWeek >= 13 && safeWeek < 16) { fallbackFruit = "Lemon"; fallbackEmoji = "🍋"; }
  else if (safeWeek >= 17 && safeWeek < 20) { fallbackFruit = "Mango"; fallbackEmoji = "🥭"; }
  else if (safeWeek >= 21 && safeWeek < 24) { fallbackFruit = "Pomegranate"; fallbackEmoji = "🍎"; }
  else if (safeWeek >= 25 && safeWeek < 28) { fallbackFruit = "Cauliflower"; fallbackEmoji = "🥦"; }
  else if (safeWeek >= 29 && safeWeek < 32) { fallbackFruit = "Butternut Squash"; fallbackEmoji = "🎃"; }
  else if (safeWeek >= 33 && safeWeek < 36) { fallbackFruit = "Pineapple"; fallbackEmoji = "🍍"; }
  else if (safeWeek >= 37 && safeWeek <= 40) { fallbackFruit = "Watermelon"; fallbackEmoji = "🍉"; }

  return {
    ...base,
    week: safeWeek,
    trimester,
    babyLengthCm: lengthEst,
    babyWeightG: weightEst,
    babySizeName: fallbackFruit,
    babySizeEmoji: fallbackEmoji,
  };
}
